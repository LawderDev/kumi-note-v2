/// Kumi Note z-index tokens for layering.
class KumiZIndex {
  KumiZIndex._();

  /// 100 - Menus déroulants
  static const int zDropdown = 100;

  /// 200 - Headers sticky
  static const int zSticky = 200;

  /// 300 - Floating action button
  static const int zFab = 300;

  /// 400 - Modals, dialogs
  static const int zModal = 400;

  /// 500 - Temporary messages (toast)
  static const int zToast = 500;

  /// 600 - Tooltips
  static const int zTooltip = 600;
}
